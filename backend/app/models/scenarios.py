import uuid
from datetime import datetime, timezone
from typing import Optional, Dict, Any, List
from sqlalchemy import (
    String, Integer, Float, DateTime, ForeignKey, CheckConstraint, Index, Numeric, Text
)
from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship
from backend.app.models.base import Base


class Scenario(Base):
    """Counterfactual what-if scenario definition created by a policy planner."""
    __tablename__ = "scenario"

    scenario_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text)
    parameters: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    results: Mapped[List["ScenarioResult"]] = relationship("ScenarioResult", back_populates="scenario", cascade="all, delete-orphan")


class ScenarioResult(Base):
    """Calculated output metrics for a simulated scenario."""
    __tablename__ = "scenario_result"

    result_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    scenario_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("scenario.scenario_id", ondelete="CASCADE"), nullable=False, index=True)
    
    baseline_gap: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    simulated_gap: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    net_reduction: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    reduction_pct: Mapped[float] = mapped_column(Float, default=0.0)
    estimated_cost_inr: Mapped[float] = mapped_column(Numeric(15, 2), default=0.0)
    confidence_score: Mapped[float] = mapped_column(Float, default=0.85)
    details: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict)
    
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    scenario: Mapped["Scenario"] = relationship("Scenario", back_populates="results")


class OptimizationRun(Base):
    """Record of a mathematical policy intervention optimization executed via OR-Tools."""
    __tablename__ = "optimization_run"

    run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    state_id: Mapped[str] = mapped_column(String(10), ForeignKey("dim_state.state_id", ondelete="RESTRICT"), nullable=False, index=True)
    horizon_months: Mapped[int] = mapped_column(Integer, default=12)
    budget_inr: Mapped[float] = mapped_column(Numeric(15, 2), nullable=False)
    
    solver_status: Mapped[str] = mapped_column(String(50), default="OPTIMAL", nullable=False)
    objective_value: Mapped[Optional[float]] = mapped_column(Numeric(15, 2))
    allocated_budget_inr: Mapped[Optional[float]] = mapped_column(Numeric(15, 2))
    solve_time_ms: Mapped[int] = mapped_column(Integer, default=0)
    parameters: Mapped[Dict[str, Any]] = mapped_column(JSONB, default=dict)
    
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    results: Mapped[List["OptimizationResult"]] = relationship("OptimizationResult", back_populates="run", cascade="all, delete-orphan")

    __table_args__ = (
        CheckConstraint("budget_inr >= 0", name="chk_opt_budget_non_neg"),
    )


class OptimizationResult(Base):
    """Ranked portfolio of recommended training interventions generated by the optimizer."""
    __tablename__ = "optimization_result"

    result_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    run_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("optimization_run.run_id", ondelete="CASCADE"), nullable=False, index=True)
    rank: Mapped[int] = mapped_column(Integer, nullable=False)
    
    center_id: Mapped[str] = mapped_column(String(50), ForeignKey("dim_training_center.center_id", ondelete="RESTRICT"), nullable=False)
    qualification_id: Mapped[str] = mapped_column(String(50), ForeignKey("dim_qualification.qualification_id", ondelete="RESTRICT"), nullable=False)
    action: Mapped[str] = mapped_column(String(50), default="EXPAND_SEATS", nullable=False)
    
    seat_delta: Mapped[int] = mapped_column(Integer, nullable=False)
    cost_inr: Mapped[float] = mapped_column(Numeric(15, 2), nullable=False)
    expected_gap_reduction: Mapped[float] = mapped_column(Numeric(12, 2), nullable=False)
    rationale: Mapped[Optional[str]] = mapped_column(Text)
    
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)

    run: Mapped["OptimizationRun"] = relationship("OptimizationRun", back_populates="results")

    __table_args__ = (
        CheckConstraint("seat_delta >= 0", name="chk_opt_result_seat_delta_non_neg"),
        CheckConstraint("cost_inr >= 0", name="chk_opt_result_cost_non_neg"),
        Index("idx_opt_result_run_rank", "run_id", "rank"),
    )
